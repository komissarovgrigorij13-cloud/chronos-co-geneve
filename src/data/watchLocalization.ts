const conditionLabels: Record<Language, Record<Watch['condition'], string>> = {
  EN: { Unworn: 'Unworn', 'Pre-Owned': 'Pre-Owned' },
  RU: { Unworn: 'Новые', 'Pre-Owned': 'Коллекционные' },
  FR: { Unworn: 'Jamais portée', 'Pre-Owned': 'Collection' },
  AR: { Unworn: 'جديدة', 'Pre-Owned': 'مقتناة سابقاً' },
};

function replaceTerms(value: string, language: Language): string {
  if (language === 'EN') return value;
  return replacements[language].reduce((result, [from, to]) => result.split(from).join(to), value);
}

function localizedDescription(watch: Watch, language: Language, variant: string, movement: string, complications: string[]): string {
  if (language === 'EN') return watch.description;

  const complicationList = complications.join(language === 'AR' ? '، ' : ', ');

  if (language === 'RU') {
    return `Коллекционный экземпляр ${watch.brand} ${watch.model} в исполнении «${variant}». Механизм — ${movement}; среди его функций: ${complicationList}. Модель прошла индивидуальную проверку происхождения и поставляется в состоянии «${conditionLabels.RU[watch.condition]}» с подтверждённой комплектацией.`;
  }

  if (language === 'FR') {
    return `Cette pièce de collection ${watch.brand} ${watch.model} se présente dans une exécution «${variant}». Elle est animée par un ${movement}, avec notamment : ${complicationList}. La montre a été contrôlée individuellement et est proposée en état «${conditionLabels.FR[watch.condition]}», avec sa provenance documentée.`;
  }

  return `قطعة ${watch.brand} ${watch.model} بإصدار «${variant}». تعمل بحركة ${movement} وتضم: ${complicationList}. خضعت الساعة لفحص فردي للأصالة وتُقدَّم بحالة «${conditionLabels.AR[watch.condition]}» مع توثيق مصدرها ومكوّناتها.`;
}

export function getLocalizedWatch(watch: Watch, language: Language): LocalizedWatchFields {
  const variant = replaceTerms(watch.variant, language);
  const movement = replaceTerms(watch.movement, language);
  const complications = watch.complications.map((complication) => replaceTerms(complication, language));

  return {
    variant,
    movement,
    material: materialLabels[language][watch.material],
    condition: conditionLabels[language][watch.condition],
    complications,
    description: localizedDescription(watch, language, variant, movement, complications),
  };
}
